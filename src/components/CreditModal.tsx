'use client';

import { useState, useEffect, useRef, useMemo } from 'react';
import Link from 'next/link';
import QRCode from 'qrcode';
import {
  X,
  Check,
  AlertCircle,
  Copy,
  ExternalLink,
  Coins,
  QrCode,
  Wallet,
  Sparkles,
  ArrowRight,
  ShieldCheck,
  ReceiptText,
} from 'lucide-react';
import { useAuth } from '../lib/firebase/auth-context';
import {
  createCryptoTransaction,
  listenToTransaction,
} from '../lib/firebase/firestore';
import { useAppKit, useAppKitAccount, useAppKitNetwork } from '@reown/appkit/react';
import { useDisconnect } from '@reown/appkit-controllers/react';
import { useChainId, useSendTransaction, useWriteContract, useSwitchChain, useBalance, useReadContracts, usePublicClient } from 'wagmi';
import { getAccount } from '@wagmi/core';
import { parseEther, parseUnits, formatUnits, type Address } from 'viem';
import { CHAIN_ID_TO_VIEM_CHAIN, CHAIN_KEY_TO_VIEM_CHAIN, getWagmiConfig } from '../lib/web3/config';
import {
  CREDIT_PACKS,
  CreditPack,
  SupportedChainKey,
  SupportedToken,
  ChainMetadata,
  ParsedPaymentWallet,
  loadPaymentWallets,
  getCachedPaymentWallets,
  getRecipientWallet,
  getAvailableChains,
  fetchLiveTokenPrices,
  getCachedTokenPrices,
  calculateCryptoAmount,
  getSupportedChains,
  getERC20Contracts,
  fetchBackendConfig,
} from '../lib/web3/payment-wallets';
import {
  fetchUserWalletAddress,
  getCachedUserWalletAddress,
} from '../lib/user-wallet';
import { ChainIcon, TokenIcon } from './ChainIcons';
import { useI18n } from '../lib/i18n';

interface CreditModalProps {
  isOpen: boolean;
  onClose: () => void;
  requiredReason?: string;
  onOpenAuth?: () => void;
}

const ERC20_ABI = [
  {
    name: 'transfer',
    type: 'function',
    stateMutability: 'nonpayable',
    inputs: [
      { name: 'recipient', type: 'address' },
      { name: 'amount', type: 'uint256' },
    ],
    outputs: [{ name: '', type: 'bool' }],
  },
] as const;

const ERC20_BALANCE_ABI = [
  {
    name: 'balanceOf',
    type: 'function',
    stateMutability: 'view',
    inputs: [{ name: 'account', type: 'address' }],
    outputs: [{ name: '', type: 'uint256' }],
  },
] as const;

export function CreditModal({ isOpen, onClose, requiredReason, onOpenAuth }: CreditModalProps) {
  const { t } = useI18n();
  const { user, refreshProfile } = useAuth();
  const { open } = useAppKit();
  const { address, isConnected } = useAppKitAccount();
  const { chainId: appKitChainId } = useAppKitNetwork();
  const wagmiChainId = useChainId();
  const currentChainId = Number(appKitChainId) || wagmiChainId;
  const { disconnect } = useDisconnect();
  const { switchChainAsync, chains } = useSwitchChain();
  const { sendTransactionAsync } = useSendTransaction();
  const { writeContractAsync } = useWriteContract();
  const publicClient = usePublicClient();

  // State
  const [selectedPack, setSelectedPack] = useState<CreditPack>(CREDIT_PACKS[1]); // default to 100 pack
  const [selectedChainKey, setSelectedChainKey] = useState<SupportedChainKey>('bsc');
  const [selectedToken, setSelectedToken] = useState<SupportedToken>('USDT');
  const [payMethod, setPayMethod] = useState<'wallet' | 'qr'>('wallet');

  // Network switching states
  const [switchFailedChainId, setSwitchFailedChainId] = useState<number | null>(null);
  const [isSwitchingChain, setIsSwitchingChain] = useState<boolean>(false);

  const [qrCodeUrl, setQrCodeUrl] = useState<string>('');
  const [copiedField, setCopiedField] = useState<string | null>(null);
  const [loading, setLoading] = useState(false);
  const [successMsg, setSuccessMsg] = useState<string | null>(null);
  const [errorMsg, setErrorMsg] = useState<string | null>(null);
  const [txHashInput, setTxHashInput] = useState<string>('');

  // Keep track of active Firestore listener unsubscribers to prevent memory leaks
  const activeUnsubscribesRef = useRef<Array<() => void>>([]);

  // Wallets loaded asynchronously from backend
  const [wallets, setWallets] = useState<ParsedPaymentWallet[]>(() => getCachedPaymentWallets() || []);
  const [isLoadingWallets, setIsLoadingWallets] = useState<boolean>(() => !getCachedPaymentWallets());

  // Chains loaded asynchronously from backend
  const [supportedChains, setSupportedChains] = useState<Record<SupportedChainKey, ChainMetadata> | null>(null);
  const [isLoadingChains, setIsLoadingChains] = useState<boolean>(true);

  // Testnet mode from backend config
  const [isTestnet, setIsTestnet] = useState<boolean>(false);

  // User's own EVM deposit wallet (generated by backend on first login).
  // Preferred recipient for all EVM chains; wallets.*.json addresses are fallback.
  const [userWalletAddress, setUserWalletAddress] = useState<string | null>(
    () => getCachedUserWalletAddress()
  );

  // Real-time token prices
  const [tokenPrices, setTokenPrices] = useState<Record<SupportedToken, number>>(() => getCachedTokenPrices());

  useEffect(() => {
    if (!isOpen) return;
    let mounted = true;
    loadPaymentWallets()
      .then((loaded) => {
        if (mounted) {
          setWallets(loaded);
          setIsLoadingWallets(false);
        }
      })
      .catch((err) => {
        console.warn('Failed to load payment wallets:', err);
        if (mounted) setIsLoadingWallets(false);
      });

    getSupportedChains()
      .then((chains) => {
        if (mounted) {
          setSupportedChains(chains);
          setIsLoadingChains(false);
        }
      })
      .catch((err) => {
        console.warn('Failed to load supported chains:', err);
        if (mounted) setIsLoadingChains(false);
      });

    fetchLiveTokenPrices(true)
      .then((prices) => {
        if (mounted) setTokenPrices(prices);
      })
      .catch((err) => {
        console.warn('Failed to fetch live token prices:', err);
      });

    fetchBackendConfig()
      .then((config) => {
        if (mounted) setIsTestnet(config.isTestnet);
      })
      .catch((err) => {
        console.warn('Failed to fetch backend config:', err);
      });

    fetchUserWalletAddress()
      .then((address) => {
        if (mounted && address) setUserWalletAddress(address);
      })
      .catch((err) => {
        console.warn('Failed to fetch user wallet address:', err);
      });

    return () => {
      mounted = false;
    };
  }, [isOpen]);

  // Dynamically derive available chains that have valid non-zero wallet addresses
  const availableChains = useMemo(
    () => getAvailableChains(wallets, supportedChains),
    [wallets, supportedChains]
  );

  // Ensure selected chain stays valid whenever available chains load or update
  // (render-time adjustment — React's recommended pattern for derived state)
  if (
    availableChains.length > 0 &&
    !availableChains.some((c) => c.key === selectedChainKey)
  ) {
    setSelectedChainKey(availableChains[0].key);
  }

  // Pre-select the chain matching the user's connected wallet on open
  const hasInitializedChainRef = useRef(false);
  useEffect(() => {
    if (isOpen && isConnected && currentChainId && !hasInitializedChainRef.current && availableChains.length > 0) {
      const matchingChain = availableChains.find((c) => c.chainId === currentChainId);
      if (matchingChain) {
        queueMicrotask(() => setSelectedChainKey(matchingChain.key));
        hasInitializedChainRef.current = true;
      }
    }
    if (!isOpen) {
      hasInitializedChainRef.current = false;
      queueMicrotask(() => {
        setSwitchFailedChainId(null);
        setIsSwitchingChain(false);
      });
    }
  }, [isOpen, isConnected, currentChainId, availableChains]);

  const chainMeta =
    supportedChains?.[selectedChainKey] ||
    availableChains[0] || {} as ChainMetadata;
  const isEvm = chainMeta?.isEvm ?? true;

  // React to wallet-initiated chain changes (e.g., user switches network in MetaMask)
  // Auto-sync selectedChainKey to match the wallet's current chain
  if (isConnected && currentChainId) {
    const matchingChain = availableChains.find((c) => c.chainId === currentChainId);
    if (matchingChain && matchingChain.key !== selectedChainKey) {
      setSelectedChainKey(matchingChain.key);
    }
  }

  // Clear failed switch notice if wallet successfully switches to selected chain
  if (currentChainId === chainMeta.chainId && switchFailedChainId !== null) {
    setSwitchFailedChainId(null);
  }

  // Refresh live token prices on user interaction (rates fluctuate)
  const refreshTokenPrices = () => {
    fetchLiveTokenPrices(true)
      .then((prices) => setTokenPrices(prices))
      .catch((err) => console.warn('Failed to refresh token prices:', err));
  };

  // Handle network card selection with automatic seamless chain switching
  const handleSelectChain = async (key: SupportedChainKey) => {
    setSelectedChainKey(key);
    setErrorMsg(null);
    setSwitchFailedChainId(null);
    refreshTokenPrices();

    const targetChain = supportedChains?.[key] || availableChains.find((c) => c.key === key);
    if (!targetChain || !targetChain.chainId) return;

    // If wallet is connected and on a different network, automatically switch to it
    if (isConnected && currentChainId && currentChainId !== targetChain.chainId) {
      const targetViemChain =
        CHAIN_ID_TO_VIEM_CHAIN[targetChain.chainId] || CHAIN_KEY_TO_VIEM_CHAIN[key];
      const addChainParams = targetViemChain
        ? {
          chainName: targetViemChain.name,
          rpcUrls: targetViemChain.rpcUrls?.default?.http ?? [],
          blockExplorerUrls: targetViemChain.blockExplorers?.default?.url
            ? [targetViemChain.blockExplorers.default.url]
            : undefined,
          nativeCurrency: targetViemChain.nativeCurrency,
        }
        : undefined;

      setIsSwitchingChain(true);
      try {
        if (switchChainAsync) {
          await switchChainAsync({
            chainId: targetChain.chainId,
            addEthereumChainParameter: addChainParams,
          });
          setSwitchFailedChainId(null);
        }
      } catch (err) {
        console.warn('[CreditModal] Auto chain switch failed or was rejected:', err);
        // Record failure so manual switch banner is only shown when auto switch fails
        setSwitchFailedChainId(targetChain.chainId);
      } finally {
        setIsSwitchingChain(false);
      }
    }
  };

  // Active token for the selected chain
  const chainTokens = chainMeta.tokens ?? [];
  const activeToken: SupportedToken = chainTokens.includes(selectedToken)
    ? selectedToken
    : chainTokens[0];

  // Recipient wallet address: the user's own EVM address when available
  // (all supported chains are EVM), otherwise the configured fallback wallet.
  const recipientWallet = useMemo(() => {
    if (userWalletAddress) return userWalletAddress;
    return getRecipientWallet(
      chainMeta.key,
      activeToken,
      wallets,
      chainMeta.chainId
    );
  }, [userWalletAddress, chainMeta.key, activeToken, wallets, chainMeta.chainId]);

  const isInvalidRecipient =
    !recipientWallet ||
    recipientWallet.startsWith('0x0000000000000000000000000000000000000000');

  // Calculate live crypto amount based on USD pack price and real-time token rates
  const amountToPay = useMemo(() => {
    return calculateCryptoAmount(selectedPack.usdPrice, activeToken, tokenPrices);
  }, [selectedPack.usdPrice, activeToken, tokenPrices]);

  // --- Balance hooks (must be after chainMeta is defined) ---

  // Native token balance for the currently connected wallet
  const { data: nativeBalanceData, isLoading: isLoadingNativeBalance } = useBalance({
    address: address as `0x${string}`,
    chainId: chainMeta.chainId,
    query: {
      enabled: isConnected && !!address && !!chainMeta.chainId,
      staleTime: 10_000,
    },
  });

  const erc20ContractCalls = useMemo(() => {
    if (!isConnected || !address || !chainMeta.chainId) return [];
    return chainTokens
      .filter((t) => t !== chainMeta.nativeToken)
      .map((token) => {
        const contract = getERC20Contracts()[chainMeta.chainId]?.[token];
        if (!contract) return null;
        return {
          address: contract.address,
          abi: ERC20_BALANCE_ABI,
          functionName: 'balanceOf' as const,
          args: [address as `0x${string}`],
          chainId: chainMeta.chainId,
          token,
          decimals: contract.decimals,
        };
      })
      .filter((c): c is NonNullable<typeof c> => c !== null);
  }, [isConnected, address, chainMeta.chainId, chainTokens, chainMeta.nativeToken]);

  const { data: erc20Results, isLoading: isLoadingErc20 } = useReadContracts({
    contracts: erc20ContractCalls,
    query: {
      enabled: erc20ContractCalls.length > 0,
      staleTime: 10_000,
    },
  });

  // Build a map of token -> balance string
  const tokenBalances = useMemo(() => {
    const balances: Record<string, string> = {};
    // Native balance
    if (nativeBalanceData) {
      balances[chainMeta.nativeToken] = formatUnits(nativeBalanceData.value, nativeBalanceData.decimals);
    }
    // ERC-20 balances
    if (erc20Results) {
      erc20ContractCalls.forEach((call, idx) => {
        const result = erc20Results[idx];
        if (result?.status === 'success' && result.result !== undefined && result.result !== null) {
          balances[call.token] = formatUnits(result.result as bigint, call.decimals);
        } else if (result?.status === 'failure') {
          balances[call.token] = '0';
        }
      });
    }
    return balances;
  }, [nativeBalanceData, erc20Results, erc20ContractCalls, chainMeta.nativeToken]);

  // Reset transient feedback state when modal opens or closes
  useEffect(() => {
    if (!isOpen) {
      queueMicrotask(() => {
        setErrorMsg(null);
        setSuccessMsg(null);
        setLoading(false);
        setTxHashInput('');
        setCopiedField(null);
      });

      // Clean up any pending Firestore listeners
      activeUnsubscribesRef.current.forEach((unsub) => unsub());
      activeUnsubscribesRef.current = [];
    }
  }, [isOpen]);

  // Clean up listeners on unmount
  useEffect(() => {
    return () => {
      activeUnsubscribesRef.current.forEach((unsub) => unsub());
      activeUnsubscribesRef.current = [];
    };
  }, []);

  // Format balance for display
  const formatBalance = (balance: string, decimals: number = 4): string => {
    const num = parseFloat(balance);
    if (isNaN(num)) return '0';
    if (num === 0) return '0';
    if (num < 0.0001) return '< 0.0001';
    if (num >= 1000) return num.toFixed(2);
    return num.toFixed(decimals).replace(/\.?0+$/, '');
  };

  // Generate QR code for the recipient wallet
  useEffect(() => {
    if (!isOpen || isLoadingWallets || isInvalidRecipient || !recipientWallet) {
      queueMicrotask(() => setQrCodeUrl(''));
      return;
    }

    let active = true;
    QRCode.toDataURL(recipientWallet, {
      width: 220,
      margin: 1,
      color: {
        dark: '#000000',
        light: '#ffffff',
      },
    })
      .then((url) => {
        if (active) setQrCodeUrl(url);
      })
      .catch(() => {
        if (active) setQrCodeUrl('');
      });

    return () => {
      active = false;
    };
  }, [isOpen, isLoadingWallets, isInvalidRecipient, recipientWallet]);

  if (!isOpen) return null;

  const copyToClipboard = (text: string, field: string) => {
    navigator.clipboard.writeText(text);
    setCopiedField(field);
    setTimeout(() => setCopiedField(null), 2000);
  };

  // Web3 / WalletConnect transaction
  const handlePayWithWeb3 = async () => {
    setErrorMsg(null);
    setSuccessMsg(null);

    // Check Google auth first before doing anything
    if (!user || user.isAnonymous) {
      if (onOpenAuth) {
        onClose();
        onOpenAuth();
      } else {
        setErrorMsg(t('modals.credits.signInFirst'));
      }
      return;
    }

    // If wallet not connected, open the wallet connector
    if (!isConnected) {
      await open();
      return;
    }

    setLoading(true);

    try {
      if (isInvalidRecipient) {
        throw new Error(t('modals.credits.walletNotConfigured', { chain: chainMeta.name }));
      }

      const targetChainId = chainMeta.chainId;
      if (!targetChainId) {
        throw new Error(t('modals.credits.noDirectTransfer'));
      }

      // 1. Switch network if needed
      const liveAccount = getAccount(getWagmiConfig());
      const activeChainId = liveAccount.chainId || Number(appKitChainId) || currentChainId;

      if (activeChainId !== targetChainId) {
        const targetViemChain = CHAIN_ID_TO_VIEM_CHAIN[targetChainId] || CHAIN_KEY_TO_VIEM_CHAIN[selectedChainKey];
        const addChainParams = targetViemChain ? {
          chainName: targetViemChain.name,
          rpcUrls: targetViemChain.rpcUrls?.default?.http ?? [],
          blockExplorerUrls: targetViemChain.blockExplorers?.default?.url ? [targetViemChain.blockExplorers.default.url] : undefined,
          nativeCurrency: targetViemChain.nativeCurrency,
        } : undefined;
        try {
          if (switchChainAsync) {
            await switchChainAsync({ chainId: targetChainId, addEthereumChainParameter: addChainParams });
          } else {
            throw new Error('switchChainAsync not available');
          }
        } catch (switchErr: unknown) {
          const errorObj = switchErr as { code?: number; name?: string; message?: string; cause?: { code?: number; name?: string } } | undefined;
          const isUserRejection = errorObj?.code === 4001 || errorObj?.cause?.code === 4001 || errorObj?.name === 'UserRejectedRequestError';
          if (isUserRejection) {
            throw new Error(t('modals.credits.switchNetworkFirst', { chain: chainMeta.name }));
          }
          // If programmatic switch fails (e.g. not configured in wallet or mobile wallet), open Reown's network modal
          console.warn('Programmatic switch failed, opening Reown network dialog:', switchErr);
          open({ view: 'Networks' });
          throw new Error(t('modals.credits.selectNetworkDialog', { chain: chainMeta.name }));
        }
      }

      // 2. Fetch current gas fees to ensure we respect the block base fee
      if (!publicClient) {
        throw new Error(t('modals.credits.networkError'));
      }
      const block = await publicClient.getBlock();
      const baseFee = block.baseFeePerGas ?? BigInt(0);

      // Estimate EIP-1559 fees from the network; fall back to baseFee + 1 Gwei tip
      let maxFeePerGas: bigint;
      let maxPriorityFeePerGas: bigint;
      try {
        const fees = await publicClient.estimateFeesPerGas();
        maxPriorityFeePerGas = fees.maxPriorityFeePerGas ?? BigInt(1000000000);
        maxFeePerGas = fees.maxFeePerGas ?? baseFee + maxPriorityFeePerGas;
      } catch {
        maxPriorityFeePerGas = BigInt(1000000000); // 1 Gwei
        maxFeePerGas = baseFee + maxPriorityFeePerGas;
      }

      // Some networks enforce a minimum priority fee (e.g. Polygon ~25 gwei)
      const MIN_PRIORITY_FEE_WEI: Record<number, bigint> = {
        137: BigInt(30_000_000_000),
        80002: BigInt(30_000_000_000),
      };
      const minTip = MIN_PRIORITY_FEE_WEI[targetChainId];
      if (minTip != null && maxPriorityFeePerGas < minTip) {
        maxPriorityFeePerGas = minTip;
        const requiredMaxFee = baseFee + maxPriorityFeePerGas;
        if (maxFeePerGas < requiredMaxFee) {
          maxFeePerGas = requiredMaxFee;
        }
      }

      // 3. Perform transaction
      let txHash = '';

      if (activeToken === chainMeta.nativeToken) {
        // Native transfer (ETH, BNB, POL, AVAX, XPL)
        const tx = await sendTransactionAsync({
          to: recipientWallet as `0x${string}`,
          value: parseEther(amountToPay),
          maxFeePerGas,
          maxPriorityFeePerGas,
        });
        txHash = tx;
      } else {
        // ERC-20 token transfer (USDT, USDC)
        const tokenConfig = getERC20Contracts()[targetChainId]?.[activeToken];
        if (!tokenConfig) {
          throw new Error(
            t('modals.credits.erc20NotConfigured', { token: activeToken, chain: chainMeta.name })
          );
        }

        const parsedAmount = parseUnits(amountToPay, tokenConfig.decimals);
        const tx = await writeContractAsync({
          address: tokenConfig.address,
          abi: ERC20_ABI,
          functionName: 'transfer',
          args: [recipientWallet as `0x${string}`, parsedAmount],
          maxFeePerGas,
          maxPriorityFeePerGas,
        });
        txHash = tx;
      }

      // 4. Record transaction in Firestore with status 'pending'
      const txId = await createCryptoTransaction({
        packId: selectedPack.id,
        credits: selectedPack.credits,
        usdPrice: selectedPack.usdPrice,
        cryptoAmount: amountToPay,
        cryptoToken: activeToken,
        chainKey: selectedChainKey,
        chainId: chainMeta.chainId,
        paymentMethod: 'web3',
        fromAddress: address || undefined,
        toAddress: recipientWallet,
        txHash,
        status: 'pending',
        statusMessage: t('modals.credits.txSubmittedOn', { chain: chainMeta.name }),
      });

      // Listen for transaction confirmation in real-time
      const unsubscribe = listenToTransaction(txId, (updatedTx) => {
        if (updatedTx?.status === 'confirmed') {
          refreshProfile();
          setSuccessMsg(
            t('modals.credits.txConfirmed', { hash: txHash.slice(0, 10), credits: selectedPack.credits })
          );
          unsubscribe();
        } else if (updatedTx?.status === 'failed') {
          setErrorMsg(t('modals.credits.txVerifyFailed'));
          unsubscribe();
        }
      });
      activeUnsubscribesRef.current.push(unsubscribe);

      setSuccessMsg(
        t('modals.credits.txSubmittedAwaiting', { chain: chainMeta.name, hash: txHash.slice(0, 10) })
      );
    } catch (err: unknown) {
      const msg = err instanceof Error ? err.message : String(err);
      if (!msg.includes('rejected') && !msg.includes('denied') && !msg.includes('User rejected')) {
        setErrorMsg(msg);
      }
    } finally {
      setLoading(false);
    }
  };

  // Manual / Direct transfer confirmation
  const handleConfirmManualPayment = async () => {
    setErrorMsg(null);
    setLoading(true);

    try {
      if (!user || user.isAnonymous) {
        throw new Error(t('modals.credits.signInFirst'));
      }

      if (isInvalidRecipient) {
        throw new Error(t('modals.credits.walletNotConfigured', { chain: chainMeta.name }));
      }

      // Record transaction in Firestore with status 'pending'
      const txId = await createCryptoTransaction({
        packId: selectedPack.id,
        credits: selectedPack.credits,
        usdPrice: selectedPack.usdPrice,
        cryptoAmount: amountToPay,
        cryptoToken: activeToken,
        chainKey: selectedChainKey,
        chainId: chainMeta.chainId,
        paymentMethod: 'direct',
        toAddress: recipientWallet,
        txHash: txHashInput.trim() || undefined,
        status: 'pending',
        statusMessage: t('modals.credits.manualStatus'),
      });

      // Listen for transaction confirmation
      const unsubscribe = listenToTransaction(txId, (updatedTx) => {
        if (updatedTx?.status === 'confirmed') {
          refreshProfile();
          setSuccessMsg(
            t('modals.credits.paymentConfirmed', { credits: selectedPack.credits })
          );
          unsubscribe();
        }
      });
      activeUnsubscribesRef.current.push(unsubscribe);

      setSuccessMsg(t('modals.credits.paymentSubmitted'));
    } catch (err: unknown) {
      const msg = err instanceof Error ? err.message : String(err);
      setErrorMsg(msg);
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/80 backdrop-blur-md p-4 animate-in fade-in duration-150">
      <div className="relative w-full max-w-2xl max-h-[92vh] overflow-y-auto rounded-3xl border border-neutral-800 bg-neutral-900/95 p-6 shadow-2xl">
        {/* Header */}
        <div className="flex items-center justify-between border-b border-neutral-800 pb-4">
          <div className="flex items-center gap-3">
            {/* eslint-disable-next-line @next/next/no-img-element */}
            <img
              src="/icon.svg"
              alt="pathify"
              className="h-10 w-10 rounded-xl border border-neutral-700/80 bg-neutral-950 p-1 object-contain shadow-md"
            />
            <div>
              <h2 className="text-base font-bold text-white flex items-center gap-2">
                <span>{t('modals.credits.title')}</span>
              </h2>
              <p className="text-xs text-neutral-400">
                {t('modals.credits.subtitle')}
              </p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="rounded-xl p-2 text-neutral-400 hover:bg-neutral-800 hover:text-white transition"
          >
            <X className="h-5 w-5" />
          </button>
        </div>

        {/* Required reason banner if opened from an action */}
        {requiredReason && (
          <div className="mt-4 flex items-center gap-2.5 rounded-xl border border-indigo-500/30 bg-indigo-500/10 p-3 text-xs text-indigo-300">
            <Sparkles className="h-4 w-4 shrink-0 text-indigo-400" />
            <span>{requiredReason}</span>
          </div>
        )}

        {/* Auth required notice */}
        {(!user || user.isAnonymous) && (
          <div className="flex items-start gap-3 rounded-xl border border-amber-500/30 bg-amber-500/10 p-3 text-xs text-amber-200">
            <AlertCircle className="h-4 w-4 shrink-0 text-amber-400 mt-0.5" />
            <div>
              <p className="font-semibold text-amber-300 mb-1">{t('modals.credits.signInRequired')}</p>
              <p className="text-amber-200/80 leading-snug">
                {t('modals.credits.signInRequiredBody')}
              </p>
              {onOpenAuth && (
                <button
                  type="button"
                  onClick={() => {
                    onClose();
                    onOpenAuth();
                  }}
                  className="mt-2 rounded-lg bg-amber-500/20 px-3 py-1.5 text-xs font-semibold text-amber-300 hover:bg-amber-500/30 transition"
                >
                  {t('modals.credits.signInWithGoogle')}
                </button>
              )}
            </div>
          </div>
        )}



        {/* Success Alert */}
        {successMsg && (
          <div className="mt-4 flex items-center justify-between gap-2.5 rounded-xl border border-emerald-500/30 bg-emerald-500/10 p-3 text-xs text-emerald-300">
            <div className="flex items-center gap-2 flex-1">
              <ShieldCheck className="h-5 w-5 shrink-0 text-emerald-400" />
              <span>{successMsg}</span>
            </div>
            <Link
              href="/transactions"
              onClick={onClose}
              className="shrink-0 underline font-semibold text-emerald-200 hover:text-white flex items-center gap-1"
            >
              <span>{t('modals.credits.transactions')}</span>
              <ArrowRight className="h-3 w-3" />
            </Link>
          </div>
        )}

        {/* Error Alert */}
        {errorMsg && (
          <div className="mt-4 flex items-center gap-2.5 rounded-xl border border-red-500/30 bg-red-500/10 p-3 text-xs text-red-300">
            <AlertCircle className="h-4 w-4 shrink-0 text-red-400" />
            <span className="flex-1">{errorMsg}</span>
          </div>
        )}

        {/* Step 1: Select Pack */}
        <div className="mt-5 space-y-2">
          <label className="text-xs font-semibold text-neutral-300 flex items-center gap-1.5">
            <Coins className="h-3.5 w-3.5 text-amber-400" />
            {t('modals.credits.selectPack')}
          </label>
          <div className="grid grid-cols-3 gap-3">
            {CREDIT_PACKS.map((pack) => {
              const isSelected = selectedPack.id === pack.id;
              return (
                <button
                  key={pack.id}
                  type="button"
                  onClick={() => {
                    setSelectedPack(pack);
                    refreshTokenPrices();
                  }}
                  className={`relative flex flex-col items-center justify-center p-3.5 rounded-2xl border transition text-center ${isSelected
                    ? 'border-indigo-500 bg-indigo-600/15 shadow-md shadow-indigo-500/10'
                    : 'border-neutral-800 bg-neutral-950/60 hover:border-neutral-700 hover:bg-neutral-900'
                    }`}
                >
                  {pack.popular && (
                    <span className="absolute -top-2.5 rounded-full bg-gradient-to-r from-indigo-500 to-purple-500 px-2 py-0.5 text-[9px] font-bold text-white shadow-sm">
                      {t('modals.credits.bestValue')}
                    </span>
                  )}
                  <div className="text-lg font-extrabold text-white">
                    {pack.credits} <span className="text-xs font-normal text-neutral-400">{t('modals.credits.creditsWord')}</span>
                  </div>
                  <div className="text-xs text-neutral-300 font-semibold mt-1">
                    ${pack.usdPrice} USD
                  </div>
                  <div className="text-[10px] text-neutral-500 mt-0.5">
                    {t('modals.credits.perSvg', { price: `$${(pack.usdPrice / pack.credits).toFixed(2)}` })}
                  </div>
                </button>
              );
            })}
          </div>
        </div>

        {/* Step 2: Choose Blockchain Network (Cards with Chain Icons) */}
        <div className="mt-5 space-y-2">
          <div className="flex items-center justify-between">
            <label className="text-xs font-semibold text-neutral-300 flex items-center gap-1.5">
              <span>{t('modals.credits.chooseNetwork')}</span>
            </label>
            <span className="text-[11px] text-neutral-400">
              {t('modals.credits.selected')} <span className="text-white font-medium">{chainMeta.name}</span>
            </span>
          </div>

          <div className="grid grid-cols-2 sm:grid-cols-3 gap-2">
            {availableChains.length === 0 ? (
              <div className="col-span-full rounded-2xl border border-neutral-800 bg-neutral-950/40 p-4 text-center text-xs text-neutral-400">
                {isLoadingWallets ? t('modals.credits.loadingNetworks') : t('modals.credits.noNetworks')}
              </div>
            ) : (
              availableChains.map((chain) => {
                const key = chain.key;
                const isSelected = selectedChainKey === key;
                return (
                  <button
                    key={key}
                    type="button"
                    onClick={() => handleSelectChain(key)}
                    style={{
                      backgroundColor: isSelected ? chain.bgGlow : undefined,
                      borderColor: isSelected ? chain.color : undefined,
                    }}
                    className={`group relative flex items-center gap-2.5 p-2.5 rounded-2xl border text-left transition-all duration-150 ${isSelected
                        ? 'shadow-md shadow-black/40 ring-1 ring-white/10'
                        : 'border-neutral-800 bg-neutral-950/60 hover:border-neutral-700 hover:bg-neutral-900/80'
                      }`}
                  >
                    {/* Chain Icon with custom network brand style */}
                    <div
                      className="relative flex h-8 w-8 shrink-0 items-center justify-center rounded-xl p-1 transition-transform group-hover:scale-105"
                      style={{
                        backgroundColor: `${chain.color}15`,
                      }}
                    >
                      <ChainIcon chainKey={key} className="h-5 w-5 object-contain" />
                    </div>

                    {/* Chain Details */}
                    <div className="min-w-0 flex-1">
                      <div className="flex items-center gap-1">
                        <span className="text-xs font-bold text-white truncate">
                          {chain.shortName}
                        </span>
                        {isSelected && (
                          <span
                            className="h-1.5 w-1.5 rounded-full shrink-0 animate-pulse"
                            style={{ backgroundColor: chain.color }}
                          />
                        )}
                      </div>
                      <div className="flex items-center gap-1.5 mt-0.5">
                        <span className="rounded bg-neutral-800/80 px-1 py-0.2 text-[9px] font-mono text-neutral-300">
                          {chain.badge}
                        </span>
                        <span className="text-[9px] text-neutral-500 font-mono">
                          EVM
                        </span>
                      </div>
                    </div>

                    {/* Active Indicator Checkmark */}
                    {isSelected && (
                      <div
                        className="absolute top-2 right-2 flex h-3.5 w-3.5 items-center justify-center rounded-full text-white shadow-sm"
                        style={{ backgroundColor: chain.color }}
                      >
                        <Check className="h-2 w-2 text-black stroke-[3]" />
                      </div>
                    )}
                  </button>
                );
              })
            )}
          </div>
        </div>

        {/* Step 3: Select Token */}
        <div className="mt-5 space-y-2">
          <label className="text-xs font-semibold text-neutral-300">
            {t('modals.credits.chooseToken', { chain: chainMeta.name })}
          </label>
          <div className="flex flex-wrap gap-2">
            {chainTokens.map((token) => {
              const isSelected = activeToken === token;
              const tokenPrice = calculateCryptoAmount(selectedPack.usdPrice, token, tokenPrices);
              const balance = tokenBalances[token];
              const isBalanceLoading = isConnected && (isLoadingNativeBalance || isLoadingErc20) && balance === undefined;
              const displayBalance = balance !== undefined
                ? `${formatBalance(balance, 4)} ${token}`
                : isBalanceLoading
                  ? t('modals.credits.balanceLoading')
                  : isConnected
                    ? `0 ${token}`
                    : null;
              return (
                <button
                  key={token}
                  type="button"
                  onClick={() => {
                    setSelectedToken(token);
                    refreshTokenPrices();
                  }}
                  className={`flex flex-col items-start gap-1 px-3 py-1.5 rounded-xl border text-xs font-medium transition min-w-[100px] ${isSelected
                      ? 'border-indigo-500 bg-indigo-600/20 text-white font-semibold'
                      : 'border-neutral-800 bg-neutral-950/60 text-neutral-400 hover:border-neutral-700 hover:text-neutral-200'
                    }`}
                >
                  <div className="flex items-center gap-2 w-full">
                    <TokenIcon token={token} className="w-4 h-4 shrink-0" />
                    <span className="font-semibold">{token}</span>
                    <span className="ml-auto rounded bg-neutral-800/80 px-1.5 py-0.5 text-[10px] text-neutral-300 font-mono">
                      {tokenPrice} {token}
                    </span>
                  </div>
                  {displayBalance && (
                    <div className={`text-[10px] font-mono ${isSelected ? 'text-indigo-300' : 'text-neutral-500'}`}>
                      {t('modals.credits.balanceLabel', { balance: displayBalance })}
                    </div>
                  )}
                </button>
              );
            })}
          </div>

        </div>

        {/* Step 4: Payment Execution Section */}
        <div className="mt-6 rounded-2xl border border-neutral-800 bg-neutral-950/80 p-4 space-y-4">
          {/* Method selector for EVM chains */}
          {isEvm ? (
            <div className="flex rounded-xl bg-neutral-900 p-1 border border-neutral-800">
              <button
                type="button"
                onClick={() => setPayMethod('wallet')}
                className={`flex-1 py-1.5 text-xs font-semibold rounded-lg flex items-center justify-center gap-1.5 transition ${payMethod === 'wallet'
                  ? 'bg-indigo-600 text-white shadow-sm'
                  : 'text-neutral-400 hover:text-white'
                  }`}
              >
                <Wallet className="h-3.5 w-3.5" />
                <span>{t('modals.credits.web3Method')}</span>
              </button>
              <button
                type="button"
                onClick={() => setPayMethod('qr')}
                className={`flex-1 py-1.5 text-xs font-semibold rounded-lg flex items-center justify-center gap-1.5 transition ${payMethod === 'qr'
                  ? 'bg-indigo-600 text-white shadow-sm'
                  : 'text-neutral-400 hover:text-white'
                  }`}
              >
                <QrCode className="h-3.5 w-3.5" />
                <span>{t('modals.credits.qrMethod')}</span>
              </button>
            </div>
          ) : (
            <div className="flex items-center justify-between text-xs text-neutral-400 border-b border-neutral-800/80 pb-2">
              <span className="font-semibold text-neutral-200 flex items-center gap-1.5">
                <QrCode className="h-4 w-4 text-indigo-400" /> {t('modals.credits.directTransfer')}
              </span>
              <span className="rounded bg-neutral-800 px-2 py-0.5 text-[10px] font-mono text-neutral-300">
                {chainMeta.badge}
              </span>
            </div>
          )}

          {/* EVM WalletConnect Tab */}
          {isEvm && payMethod === 'wallet' ? (
            <div className="space-y-4">
              {!isConnected ? (
                <div className="flex items-start gap-3 rounded-xl border border-indigo-500/30 bg-indigo-500/10 p-3 text-xs text-indigo-200">
                  <Wallet className="h-4 w-4 shrink-0 text-indigo-400 mt-0.5" />
                  <div>
                    <p className="font-semibold text-indigo-300 mb-1">{t('modals.credits.walletNotConnected')}</p>
                    <p className="text-indigo-200/80 leading-snug">
                      {t('modals.credits.walletNotConnectedBody')}
                    </p>
                  </div>
                </div>
              ) : (
                <div className="flex items-start gap-3 rounded-xl border border-emerald-500/30 bg-emerald-500/10 p-3 text-xs text-emerald-200">
                  <Check className="h-4 w-4 shrink-0 text-emerald-400 mt-0.5" />
                  <div className="flex-1">
                    <p className="font-semibold text-emerald-300 mb-1">{t('modals.credits.walletConnected')}</p>
                    <p className="font-mono text-emerald-200/80">{address?.slice(0, 6)}...{address?.slice(-4)}</p>
                  </div>
                  <button
                    type="button"
                    onClick={() => disconnect()}
                    className="shrink-0 rounded-lg bg-neutral-800 px-2.5 py-1.5 text-[11px] font-semibold text-neutral-300 hover:bg-neutral-700 hover:text-white transition"
                  >
                    {t('modals.credits.disconnect')}
                  </button>
                </div>
              )}

              {/* Network mismatch notice & manual switch button */}
              {isConnected && currentChainId && currentChainId !== chainMeta.chainId && (
                <div className="flex items-center justify-between gap-2 rounded-xl border border-amber-500/30 bg-amber-500/10 p-2.5 text-xs text-amber-200">
                  <div className="flex items-center gap-2">
                    <AlertCircle className="h-4 w-4 shrink-0 text-amber-400" />
                    <span>
                      {t('modals.credits.networkMismatchPrefix')}<strong>{chainMeta.name}</strong>{t('modals.credits.networkMismatchSuffix')}
                    </span>
                  </div>
                  <button
                    type="button"
                    onClick={async () => {
                      const targetViemChain = CHAIN_ID_TO_VIEM_CHAIN[chainMeta.chainId] || CHAIN_KEY_TO_VIEM_CHAIN[selectedChainKey];
                      const addChainParams = targetViemChain ? {
                        chainName: targetViemChain.name,
                        rpcUrls: targetViemChain.rpcUrls?.default?.http ?? [],
                        blockExplorerUrls: targetViemChain.blockExplorers?.default?.url ? [targetViemChain.blockExplorers.default.url] : undefined,
                        nativeCurrency: targetViemChain.nativeCurrency,
                      } : undefined;
                      try {
                        if (switchChainAsync) {
                          await switchChainAsync({ chainId: chainMeta.chainId, addEthereumChainParameter: addChainParams });
                        } else {
                          open({ view: 'Networks' });
                        }
                      } catch {
                        open({ view: 'Networks' });
                      }
                    }}
                    className="shrink-0 rounded-lg bg-amber-500/20 px-2.5 py-1 text-[11px] font-semibold text-amber-300 hover:bg-amber-500/30 transition cursor-pointer"
                  >
                    {t('modals.credits.switchNetwork')}
                  </button>
                </div>
              )}

              <div className="flex items-center justify-between rounded-xl bg-neutral-900/60 p-3 border border-neutral-800 text-xs">
                <div>
                  <span className="text-neutral-400 block text-[11px]">{t('modals.credits.totalToSend')}</span>
                  <span className="text-base font-bold text-white flex items-center gap-1.5">
                    <TokenIcon token={activeToken} className="w-4 h-4 shrink-0" />
                    <span>{amountToPay} {activeToken}</span>
                  </span>
                </div>
                <div className="text-right">
                  <span className="text-neutral-400 block text-[11px]">{t('modals.credits.network')}</span>
                  <span className="font-semibold text-neutral-200">{chainMeta.name}</span>
                </div>
              </div>

              <button
                type="button"
                disabled={loading || isLoadingWallets || isInvalidRecipient}
                onClick={handlePayWithWeb3}
                className="flex w-full items-center justify-center gap-2 rounded-2xl bg-indigo-600 py-3 text-sm font-semibold text-white shadow-lg shadow-indigo-500/20 hover:bg-indigo-500 transition disabled:opacity-50"
              >
                {loading ? (
                  <div className="h-4 w-4 animate-spin rounded-full border-2 border-white border-t-transparent" />
                ) : isLoadingWallets ? (
                  <span>{t('modals.credits.loadingConfig')}</span>
                ) : isInvalidRecipient ? (
                  <span>{t('modals.credits.networkNotConfigured')}</span>
                ) : !user || user.isAnonymous ? (
                  <>
                    <AlertCircle className="h-4 w-4" />
                    <span>{t('modals.credits.signInToPay', { amount: amountToPay, token: activeToken })}</span>
                    <ArrowRight className="h-4 w-4" />
                  </>
                ) : !isConnected ? (
                  <>
                    <Wallet className="h-4 w-4" />
                    <span>{t('modals.credits.connectWalletPay', { amount: amountToPay, token: activeToken })}</span>
                    <ArrowRight className="h-4 w-4" />
                  </>
                ) : (
                  <>
                    <Wallet className="h-4 w-4" />
                    <span>{t('modals.credits.sendPayment', { amount: amountToPay, token: activeToken, chain: chainMeta.name })}</span>
                    <ArrowRight className="h-4 w-4" />
                  </>
                )}
              </button>
            </div>
          ) : (
            /* Direct Transfer / QR Code Interface (Supports BTC and EVM) */
            <div className="space-y-4">
              <div className="flex flex-col sm:flex-row gap-4 items-center">
                {/* QR Code */}
                {isLoadingWallets ? (
                  <div className="h-32 w-32 rounded-xl bg-neutral-800 animate-pulse shrink-0 flex items-center justify-center text-[10px] text-neutral-500 font-mono">
                    {t('modals.credits.loadingQr')}
                  </div>
                ) : qrCodeUrl ? (
                  <div className="rounded-xl bg-white p-2 shrink-0 shadow-lg">
                    {/* eslint-disable-next-line @next/next/no-img-element */}
                    <img
                      src={qrCodeUrl}
                      alt={t('modals.credits.qrAlt')}
                      className="h-32 w-32 object-contain"
                    />
                  </div>
                ) : (
                  <div className="h-32 w-32 rounded-xl bg-neutral-800 animate-pulse shrink-0 flex items-center justify-center text-[10px] text-neutral-500 font-mono">
                    {isInvalidRecipient ? t('modals.credits.noWalletConfigured') : t('modals.credits.generatingQr')}
                  </div>
                )}

                {/* Address & Amount Copy */}
                <div className="flex-1 w-full space-y-2.5">
                  <div>
                    <label className="text-[11px] font-medium text-neutral-400 block mb-1">
                      {t('modals.credits.recipientAddress', { badge: chainMeta.badge })}
                    </label>
                    <div className="flex items-center gap-2 rounded-xl border border-neutral-800 bg-neutral-900 p-2">
                      <span className="font-mono text-xs text-neutral-200 truncate flex-1 select-all">
                        {isLoadingWallets ? (
                          <span className="text-neutral-500 animate-pulse">{t('modals.credits.loadingAddress')}</span>
                        ) : isInvalidRecipient ? (
                          <span className="text-amber-400">{t('modals.credits.walletNotConfiguredForNetwork')}</span>
                        ) : (
                          recipientWallet
                        )}
                      </span>
                      <button
                        type="button"
                        disabled={isLoadingWallets || isInvalidRecipient}
                        onClick={() => copyToClipboard(recipientWallet, 'address')}
                        className="rounded-lg bg-neutral-800 p-1.5 text-neutral-300 hover:text-white transition disabled:opacity-40"
                        title={t('modals.credits.copyAddress')}
                      >
                        {copiedField === 'address' ? (
                          <Check className="h-3.5 w-3.5 text-emerald-400" />
                        ) : (
                          <Copy className="h-3.5 w-3.5" />
                        )}
                      </button>
                    </div>
                  </div>

                  <div>
                    <label className="text-[11px] font-medium text-neutral-400 block mb-1">
                      {t('modals.credits.exactAmount')}
                    </label>
                    <div className="flex items-center gap-2 rounded-xl border border-neutral-800 bg-neutral-900 p-2">
                      <span className="font-mono text-xs font-semibold text-amber-300 truncate flex-1 flex items-center gap-1.5">
                        <TokenIcon token={activeToken} className="w-4 h-4 shrink-0" />
                        <span>{amountToPay} {activeToken}</span>
                      </span>
                      <button
                        type="button"
                        onClick={() => copyToClipboard(amountToPay, 'amount')}
                        className="rounded-lg bg-neutral-800 p-1.5 text-neutral-300 hover:text-white transition"
                        title={t('modals.credits.copyAmount')}
                      >
                        {copiedField === 'amount' ? (
                          <Check className="h-3.5 w-3.5 text-emerald-400" />
                        ) : (
                          <Copy className="h-3.5 w-3.5" />
                        )}
                      </button>
                    </div>
                  </div>
                </div>
              </div>

              {/* Safety Network Warning */}
              <div className="rounded-xl border border-amber-500/20 bg-amber-500/5 p-2.5 text-[11px] text-amber-400/90 leading-relaxed">
                ⚠️ <strong>{t('modals.credits.safetyStrong')}</strong>{t('modals.credits.safetyBody1')}
                <strong className="text-white">{activeToken}</strong>{t('modals.credits.safetyBody2')}
                <strong className="text-white">{chainMeta.badge}</strong>{t('modals.credits.safetyBody3')}
              </div>

              {/* Optional TX Hash Input & Confirmation Button */}
              <div className="pt-2 border-t border-neutral-800 space-y-2">
                <input
                  type="text"
                  placeholder={t('modals.credits.txHashPlaceholder')}
                  value={txHashInput}
                  onChange={(e) => setTxHashInput(e.target.value)}
                  className="w-full rounded-xl border border-neutral-800 bg-neutral-900 px-3 py-2 text-xs text-neutral-200 placeholder-neutral-600 focus:border-indigo-500 focus:outline-none"
                />

                <button
                  type="button"
                  disabled={loading || isLoadingWallets || isInvalidRecipient}
                  onClick={handleConfirmManualPayment}
                  className="flex w-full items-center justify-center gap-2 rounded-xl bg-emerald-600 py-2.5 text-xs font-semibold text-white shadow-md hover:bg-emerald-500 transition disabled:opacity-50"
                >
                  {loading ? (
                    <div className="h-4 w-4 animate-spin rounded-full border-2 border-white border-t-transparent" />
                  ) : isLoadingWallets ? (
                    <span>{t('modals.credits.loadingConfig')}</span>
                  ) : isInvalidRecipient ? (
                    <span>{t('modals.credits.addressNotConfigured')}</span>
                  ) : (
                    <>
                      <Check className="h-4 w-4" />
                      <span>{t('modals.credits.iHaveSent', { credits: selectedPack.credits })}</span>
                    </>
                  )}
                </button>
              </div>
            </div>
          )}
        </div>

        {/* Footer info */}
        <div className="mt-4 flex flex-col sm:flex-row items-center justify-between gap-2 text-[11px] text-neutral-500">
          <div className="flex items-center gap-2.5 flex-wrap">
            <span>{t('modals.credits.supportedChains')}</span>
            <span>•</span>
            <Link
              href="/transactions"
              onClick={onClose}
              className="flex items-center gap-1 text-indigo-400 hover:text-indigo-300 transition underline"
            >
              <ReceiptText className="h-3 w-3" />
              <span>{t('modals.credits.viewTransactions')}</span>
            </Link>
          </div>
          {chainMeta.explorerUrl && (
            <a
              href={chainMeta.explorerUrl}
              target="_blank"
              rel="noopener noreferrer"
              className="flex items-center gap-1 hover:text-neutral-400 transition shrink-0"
            >
              <span>{t('modals.credits.explorer', { chain: chainMeta.name })}</span>
              <ExternalLink className="h-3 w-3" />
            </a>
          )}
        </div>

        {/* Error Warning Dialog — fixed overlay on top of the modal */}
        {errorMsg && (
          <div className="fixed inset-0 z-[60] flex items-center justify-center bg-black/60 backdrop-blur-sm p-4 animate-in fade-in duration-150">
            <div className="w-full max-w-sm rounded-2xl border border-red-500/30 bg-neutral-900 p-5 shadow-2xl">
              <div className="flex items-center gap-3 mb-3">
                <div className="flex h-10 w-10 shrink-0 items-center justify-center rounded-full bg-red-500/20">
                  <AlertCircle className="h-5 w-5 text-red-400" />
                </div>
                <h3 className="text-sm font-semibold text-red-300">{t('modals.credits.paymentError')}</h3>
              </div>
              <p className="mb-4 text-xs text-neutral-300 leading-relaxed">{errorMsg}</p>
              <button
                type="button"
                onClick={() => setErrorMsg(null)}
                className="w-full rounded-xl bg-red-600 py-2.5 text-xs font-semibold text-white hover:bg-red-500 transition"
              >
                {t('modals.credits.dismiss')}
              </button>
            </div>
          </div>
        )}
      </div>
    </div>
  );
}
